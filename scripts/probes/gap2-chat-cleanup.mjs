import pg from 'pg'; import { readFileSync } from 'node:fs'; import { purgeUsers } from '../lib/purge.mjs';
const env = Object.fromEntries(readFileSync(new URL('../../apps/api/.env', import.meta.url), 'utf8').split('\n').filter((l) => l.includes('=') && !l.trimStart().startsWith('#')).map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim().replace(/^["']|["']$/g, '')]));
const pool = new pg.Pool({ connectionString: env.DATABASE_URL });
const ids = (await pool.query(`SELECT id FROM users WHERE id LIKE 'gapc-%'`)).rows.map((r) => r.id);
await purgeUsers(pool, ids);
const f = await pool.query(`DELETE FROM files WHERE owner_id = ANY($1::text[]) RETURNING id`, [ids]).catch((e) => ({ rowCount: e.message }));
console.log('files deleted', f.rowCount);
await purgeUsers(pool, ids);
console.log('left', (await pool.query(`SELECT count(*) FROM users WHERE id LIKE 'gapc-%'`)).rows[0]);
await pool.end();
